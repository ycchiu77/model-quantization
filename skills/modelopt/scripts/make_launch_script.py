#!/usr/bin/env python3
"""Write launch_vllm.sh into a quantized export folder, with the serving settings verified in Step 4/4b.

The generated script serves the folder it lives in (so it still works if the folder is moved),
and takes start (default) | stop | logs | status. Settings can be overridden per run with env
vars (PORT, GPU_MEM, MAX_LEN, IMAGE, CONTAINER).

    python3 make_launch_script.py --export-dir <host-output-dir>/<model-name>-<qformat> \\
        --image vllm/vllm-openai:v0.27.1 --port 8000 --max-model-len 32768 --gpu-memory-utilization 0.5 \\
        [--disabled-kernels K1,K2] [--env KEY=VAL ...] -- [--trust-remote-code --reasoning-parser qwen3 ...]

Platform (x86 discrete GPU vs Jetson) is detected via /etc/nv_tegra_release, like kernel_sweep.py.
"""
import argparse
import json
import os
import shlex
import stat
from pathlib import Path

IS_JETSON = os.path.exists("/etc/nv_tegra_release")

TEMPLATE = r"""#!/bin/bash
# Serve this quantized checkpoint with vLLM. Generated by the modelopt skill on {date}.
# Checkpoint: {quant_algo}, KV cache {kv}, platform {platform}.
# usage: ./launch_vllm.sh [start|stop|logs|status]
# override per run: PORT=8001 GPU_MEM=0.4 MAX_LEN=8192 IMAGE=... CONTAINER=... ./launch_vllm.sh
set -u
HERE="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
IMAGE="${{IMAGE:-{image}}}"
CONTAINER="${{CONTAINER:-{container}}}"
SERVED_NAME="${{SERVED_NAME:-{served_name}}}"
PORT="${{PORT:-{port}}}"
GPU_MEM="${{GPU_MEM:-{gpu_mem}}}"
MAX_LEN="${{MAX_LEN:-{max_len}}}"
CACHE="${{CACHE:-{cache}}}"   # vLLM / Triton / torch.compile caches: reused across restarts

case "${{1:-start}}" in
  stop)   docker stop "$CONTAINER"; exit ;;
  logs)   docker logs -f "$CONTAINER"; exit ;;
  status) docker ps -a --filter "name=^$CONTAINER$" --format '{{{{.Names}}}} {{{{.Status}}}}'
          curl -sf "localhost:$PORT/v1/models" >/dev/null && echo "serving on :$PORT" || echo "not serving"; exit ;;
  start)  ;;
  *)      echo "usage: $0 [start|stop|logs|status]"; exit 2 ;;
esac

if [ -n "$(docker ps -q --filter "name=^$CONTAINER$")" ]; then
  echo "$CONTAINER is already running (./launch_vllm.sh stop first)"; exit 1
fi
if ss -ltn 2>/dev/null | grep -q ":$PORT "; then
  echo "port $PORT is in use; pick another: PORT=<n> $0"; exit 1
fi
mkdir -p "$CACHE/vllm" "$CACHE/triton" "$CACHE/torch"
docker rm "$CONTAINER" >/dev/null 2>&1   # an old stopped one (no --rm: a failed run keeps its logs)
docker run -d --name "$CONTAINER" {gpu_flags} --ipc=host --shm-size 2g{extra_docker} \
  -p "$PORT:8000" \
  -e HF_HUB_OFFLINE=1{env} \
  -v "$HERE:/model:ro" \
  -v "$CACHE/vllm:/root/.cache/vllm" -v "$CACHE/triton:/root/.triton" -v "$CACHE/torch:/root/.cache/torch" \
  {entrypoint}"$IMAGE" \
  {serve_cmd}/model --served-model-name "$SERVED_NAME" \
  --max-model-len "$MAX_LEN" --gpu-memory-utilization "$GPU_MEM"{vllm_args} || exit 1

echo "starting $CONTAINER (first start compiles kernels; can take minutes)..."
s=$(date +%s)
until curl -sf "localhost:$PORT/v1/models" >/dev/null; do
  if [ -z "$(docker ps -q --filter "name=^$CONTAINER$")" ]; then
    echo "server exited:"; docker logs "$CONTAINER" 2>&1 | grep -E "Error|error" | tail -5; exit 1
  fi
  [ $(( $(date +%s) - s )) -gt {timeout} ] && {{ echo "not ready after {timeout}s; see: $0 logs"; exit 1; }}
  sleep 5
done
echo "ready in $(( $(date +%s) - s ))s on http://localhost:$PORT/v1 (model name: $SERVED_NAME)"
docker logs "$CONTAINER" 2>&1 | grep -oE "Detected ModelOpt [^ ]+ checkpoint|(Selected|Using) [A-Za-z0-9]+Kernel[^,]*" | sort -u
cat <<EOF
try it:
  curl -s localhost:$PORT/v1/chat/completions -H "Content-Type: application/json" \\
    -d '{{"model": "$SERVED_NAME", "messages": [{{"role": "user", "content": "Hello!"}}], "max_tokens": 100}}'
stop: $0 stop
EOF
"""


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--export-dir", required=True, help="host path of the quantized export (has hf_quant_config.json)")
    p.add_argument("--image", required=True, help="the same <image> used in Steps 3-5")
    p.add_argument("--port", default="8000")
    p.add_argument("--max-model-len", required=True)
    p.add_argument("--gpu-memory-utilization", required=True)
    p.add_argument("--gpu", required=not IS_JETSON, help="device index (x86, required); ignored on Jetson")
    p.add_argument("--gpu-flags", help="override docker GPU flags")
    p.add_argument("--served-name", help="default: export folder name")
    p.add_argument("--container", help="default: vllm-<served name>")
    p.add_argument("--cache-dir", help="host dir for compile caches; default: <export-dir>/../.vllm-cache")
    p.add_argument("--disabled-kernels", default="", help="VLLM_DISABLED_KERNELS from Step 4b (and Step 4's FlashInfer list if needed)")
    p.add_argument("--env", action="append", default=[], help="KEY=VAL for the server; repeatable")
    p.add_argument("--entrypoint-override", action="store_true",
                   help="image's entrypoint isn't `vllm serve` (some Jetson builds): run `vllm serve` explicitly")
    p.add_argument("--timeout", type=int, default=1800 if IS_JETSON else 900)
    p.add_argument("vllm_args", nargs=argparse.REMAINDER, help="after --: extra vllm serve args")
    a = p.parse_args()

    d = Path(a.export_dir).resolve()
    q = json.loads((d / "hf_quant_config.json").read_text())["quantization"]
    served = a.served_name or d.name
    gpu_flags = a.gpu_flags or ("--runtime=nvidia --gpus all" if IS_JETSON else f"--gpus '\"device={a.gpu}\"'")
    env = [e for e in a.env]
    if a.disabled_kernels:
        env.append(f"VLLM_DISABLED_KERNELS={a.disabled_kernels}")
    vargs = [x for x in a.vllm_args if x != "--"]
    if any(x == "--quantization" or x.startswith("--quantization=") for x in vargs):
        p.error("don't pass --quantization: vLLM detects modelopt from hf_quant_config.json (Step 4)")

    from datetime import date
    script = TEMPLATE.format(
        date=date.today().isoformat(), quant_algo=q.get("quant_algo"),
        kv=q.get("kv_cache_quant_algo") or "BF16", platform="Jetson" if IS_JETSON else "x86",
        image=a.image, container=a.container or f"vllm-{served}", served_name=served, port=a.port,
        gpu_mem=a.gpu_memory_utilization, max_len=a.max_model_len,
        cache=a.cache_dir or str(d.parent / ".vllm-cache"),
        gpu_flags=gpu_flags,
        extra_docker=" --ulimit memlock=-1 --ulimit stack=67108864" if IS_JETSON else "",
        env="".join(f" \\\n  -e {shlex.quote(e)}" for e in env),
        entrypoint='--entrypoint "" ' if a.entrypoint_override else "",
        serve_cmd="vllm serve " if a.entrypoint_override else "",
        vllm_args="".join(f" {shlex.quote(x)}" for x in vargs),
        timeout=a.timeout,
    )
    out = d / "launch_vllm.sh"
    out.write_text(script)
    out.chmod(out.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
